-- ESTADO ATUAL — FUNÇÕES
-- ============================================================================

-- Cria a linha em profiles automaticamente quando um novo usuário se
-- cadastra em auth.users. SECURITY DEFINER: precisa ignorar RLS de profiles
-- para conseguir inserir a primeira linha do usuário recém-criado.
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
as $function$
begin
  insert into public.profiles (id) values (new.id);
  return new;
end;
$function$;

-- Mantém updated_at sempre atual em apostas. SECURITY INVOKER (padrão):
-- roda com a permissão de quem chamou, respeitando o RLS normalmente —
-- só toca na própria linha que o usuário já tem permissão de UPDATE.
create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $function$
begin
    new.updated_at = now();
    return new;
end;
$function$;

-- Contadores de uso de IA, um por funcionalidade + um total geral.
-- Todas SECURITY DEFINER: precisam ignorar RLS de profiles para gravar o
-- contador do usuário sem exigir política de UPDATE liberada para ele.
create or replace function public.increment_ai_calls_count()
returns void
language sql
security definer
as $function$
  update public.profiles
  set ai_calls_count = ai_calls_count + 1
  where id = auth.uid();
$function$;

create or replace function public.increment_ai_calls_bilhete()
returns void
language sql
security definer
as $function$
  update public.profiles
  set ai_calls_bilhete = ai_calls_bilhete + 1,
      ai_calls_count = ai_calls_count + 1
  where id = auth.uid();
$function$;

create or replace function public.increment_ai_calls_estatisticas()
returns void
language sql
security definer
as $function$
  update public.profiles
  set ai_calls_estatisticas = ai_calls_estatisticas + 1,
      ai_calls_count = ai_calls_count + 1
  where id = auth.uid();
$function$;

create or replace function public.increment_ai_calls_liga()
returns void
language sql
security definer
as $function$
  update public.profiles
  set ai_calls_liga = ai_calls_liga + 1,
      ai_calls_count = ai_calls_count + 1
  where id = auth.uid();
$function$;


-- ============================================================================
-- ESTADO ATUAL — GATILHOS (TRIGGERS)
-- ============================================================================

-- Dispara em auth.users (schema do próprio Supabase Auth), não em public.
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

create trigger apostas_set_updated_at
  before update on public.apostas
  for each row execute function public.set_updated_at();


