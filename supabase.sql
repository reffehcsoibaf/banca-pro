-- ---- apostas ----
create table public.apostas (
  id uuid not null default gen_random_uuid() primary key,
  user_id uuid not null default auth.uid(),                 -- references auth.users(id), não confirmado por leitura direta (ver ressalva 1)
  identificador text not null,
  data_hora timestamp without time zone not null,
  casa text,
  tipster text,
  tipo text,
  status text not null default 'Aberto',
  stake numeric not null default 0,
  odd_total numeric not null default 0,
  recebido numeric not null default 0,
  lucro numeric not null default 0,
  unidades numeric not null default 0,
  roi numeric not null default 0,
  created_at timestamp with time zone not null default now(),
  updated_at timestamp with time zone not null default now(),
  bonus numeric not null default 0,
  observacao text,
  cash_out_valor numeric,
  constraint apostas_user_identificador_unique unique (user_id, identificador)
);

-- ---- eventos ----
create table public.eventos (
  id uuid not null default gen_random_uuid() primary key,
  aposta_id uuid not null references public.apostas(id),
  user_id uuid not null default auth.uid(),                 -- references auth.users(id), ver ressalva 1
  numero integer not null default 1,
  esporte text,
  liga text,
  evento text,
  mercado text,
  selecao text,
  odd numeric not null default 0
);

-- ---- opcoes ----
create table public.opcoes (
  id uuid not null default gen_random_uuid() primary key,
  user_id uuid not null default auth.uid(),                 -- references auth.users(id), ver ressalva 1
  campo text not null,
  valor text not null
);

-- ---- transacoes ----
create table public.transacoes (
  id uuid not null default gen_random_uuid() primary key,
  user_id uuid not null default auth.uid(),                 -- references auth.users(id), ver ressalva 1
  casa text not null,
  tipo text not null,
  valor numeric not null,
  data timestamp without time zone not null,
  observacao text,
  created_at timestamp with time zone not null default now()
);

-- ---- correcoes_ia (criada na v1.13.0 — Correções Aprendidas) ----
create table public.correcoes_ia (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid(),                 -- references auth.users(id), ver ressalva 1
  campo text not null,
  esporte text not null,
  valor_errado text not null,
  valor_correto text not null,
  contexto text,
  criado_em timestamp with time zone not null default now()
);

-- ---- profiles ----
-- Populada automaticamente pelo gatilho on_auth_user_created (ver abaixo)
-- a cada novo cadastro em auth.users — não é inserida manualmente pelo app.
create table public.profiles (
  id uuid not null primary key references auth.users(id),
  is_admin boolean not null default false,
  created_at timestamp with time zone not null default now(),
  ai_enabled boolean not null default false,
  ai_calls_count integer not null default 0,
  ai_calls_bilhete integer not null default 0,
  ai_calls_estatisticas integer not null default 0,
  ai_calls_liga integer not null default 0
);


-- ============================================================================
-- ESTADO ATUAL — ROW LEVEL SECURITY (RLS)
-- ============================================================================
-- Todas as tabelas com dado do usuário têm RLS ativado, restringindo cada
-- linha ao próprio dono (auth.uid() = user_id). "profiles" é a exceção: só
-- tem política de leitura (SELECT) da própria linha — updates em profiles
-- acontecem só via as funções SECURITY DEFINER abaixo, que ignoram RLS de
-- propósito.

alter table public.apostas enable row level security;
alter table public.eventos enable row level security;
alter table public.opcoes enable row level security;
alter table public.transacoes enable row level security;
alter table public.correcoes_ia enable row level security;
alter table public.profiles enable row level security;

create policy "apostas: somente o proprio usuario"
  on public.apostas for all
  using (auth.uid() = user_id)
  with check (auth.uid() = user_id);

create policy "eventos: somente o proprio usuario"
  on public.eventos for all
  using (auth.uid() = user_id)
  with check (auth.uid() = user_id);

create policy "opcoes: somente o proprio usuario"
  on public.opcoes for all
  using (auth.uid() = user_id)
  with check (auth.uid() = user_id);

create policy "transacoes: somente o proprio usuario"
  on public.transacoes for all
  using (auth.uid() = user_id)
  with check (auth.uid() = user_id);

create policy "Usuarios gerenciam suas proprias correcoes"
  on public.correcoes_ia for all
  using (auth.uid() = user_id)
  with check (auth.uid() = user_id);

create policy "usuarios veem o proprio perfil"
  on public.profiles for select
  using (auth.uid() = id);


